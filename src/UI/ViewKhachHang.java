    private void tblKhachHangMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblKhachHangMouseClicked

        int row = tblKhachHang.getSelectedRow();
        if (row >= 0) {
            // Hiển thị dữ liệu từ bảng lên form
            txtMa.setText(getSafeString(tblKhachHang.getValueAt(row, 0))); // Mã khách hàng (cột 0)
            txtTen.setText(getSafeString(tblKhachHang.getValueAt(row, 1))); // Tên khách hàng (cột 1)
            txtSdt.setText(getSafeString(tblKhachHang.getValueAt(row, 2))); // Số điện thoại (cột 2)
            txtDiaChi.setText(getSafeString(tblKhachHang.getValueAt(row, 3))); // Địa chỉ (cột 3)

            // Xử lý điểm tích lũy: loại bỏ ".0" và định dạng với dấu phẩy
            String diemTichLuyStr = tblKhachHang.getValueAt(row, 4).toString().replace(",", ""); // Loại bỏ dấu phẩy hiện có
            try {
                BigDecimal diemTichLuy = new BigDecimal(diemTichLuyStr);
                // Định dạng với dấu phẩy, bỏ phần thập phân .0
                DecimalFormat df = new DecimalFormat("#,###");
                txtDiemTichLuy.setText(df.format(diemTichLuy));
            } catch (NumberFormatException e) {
                // Nếu không parse được, giữ nguyên giá trị đã loại bỏ dấu phẩy
                txtDiemTichLuy.setText(diemTichLuyStr);
            }

        }
    }//GEN-LAST:event_tblKhachHangMouseClicked

    private void btnsuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsuaActionPerformed
        int confirm = JOptionPane.showConfirmDialog(this, "Bạn có muốn sửa thông tin khách hàng này không?", "Xác nhận", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        try {
            // Lấy thông tin từ giao diện (không trim ngay để kiểm tra khoảng trống)
            String maKhachHangStr = txtMa.getText();
            String tenKhachHangInput = txtTen.getText();
            String soDienThoaiInput = txtSdt.getText();
            String diaChiInput = txtDiaChi.getText();
            String diemTichLuyStrInput = txtDiemTichLuy.getText();

            // Kiểm tra khoảng trống ở đầu hoặc cuối
            if (!tenKhachHangInput.equals(tenKhachHangInput.trim())) {
                JOptionPane.showMessageDialog(this, "Tên khách hàng không được chứa khoảng trống ở đầu hoặc cuối");
                txtTen.requestFocus();
                return;
            }
            if (!soDienThoaiInput.equals(soDienThoaiInput.trim())) {
                JOptionPane.showMessageDialog(this, "Số điện thoại không được chứa khoảng trống ở đầu hoặc cuối");
                txtSdt.requestFocus();
                return;
            }
            if (!diaChiInput.equals(diaChiInput.trim())) {
                JOptionPane.showMessageDialog(this, "Địa chỉ không được chứa khoảng trống ở đầu hoặc cuối");
                txtDiaChi.requestFocus();
                return;
            }
            if (!diemTichLuyStrInput.equals(diemTichLuyStrInput.trim())) {
                JOptionPane.showMessageDialog(this, "Điểm tích lũy không được chứa khoảng trống ở đầu hoặc cuối");
                txtDiemTichLuy.requestFocus();
                return;
            }

            // Trim sau khi kiểm tra
            String tenKhachHang = tenKhachHangInput.trim();
            String soDienThoai = soDienThoaiInput.trim();
            String diaChi = diaChiInput.trim();
            String diemTichLuyStr = diemTichLuyStrInput.trim();

            // Kiểm tra các trường không được để trống
            if (tenKhachHang.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Bạn chưa nhập tên khách hàng");
                txtTen.requestFocus();
                return;
            }
            if (soDienThoai.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Bạn chưa nhập số điện thoại");
                txtSdt.requestFocus();
                return;
            }
            if (diaChi.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Bạn chưa nhập địa chỉ");
                txtDiaChi.requestFocus();
                return;
            }
            if (diemTichLuyStr.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Bạn chưa nhập điểm tích lũy");
                txtDiemTichLuy.requestFocus();
                return;
            }

            // Parse MaKhachHang (vì là int)
            int maKhachHang;
            try {
                maKhachHang = Integer.parseInt(maKhachHangStr);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Mã khách hàng không hợp lệ");
                txtMa.requestFocus();
                return;
            }

            // Validate và parse DiemTichLuy (hỗ trợ dấu phẩy)
            int diemTichLuy;
            try {
                String diemTichLuyStrCleaned = diemTichLuyStr.replace(".", ""); // Loại bỏ dấu chấm nếu có
                if (diemTichLuyStrCleaned.contains(",")) {
                    JOptionPane.showMessageDialog(this, "Điểm tích lũy không được chứa dấu phẩy (,)");
                    txtDiemTichLuy.requestFocus();
                    return;
                }
                diemTichLuy = Integer.parseInt(diemTichLuyStrCleaned);
                if (diemTichLuy < 0) {
                    JOptionPane.showMessageDialog(this, "Điểm tích lũy không được âm");
                    txtDiemTichLuy.requestFocus();
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this, "Điểm tích lũy phải là số nguyên dương");
                txtDiemTichLuy.requestFocus();
                return;
            }

            // Gọi phương thức cập nhật
            KhachHangRepository repository = new KhachHangRepository();
            boolean isUpdated = repository.updateKhachHang(maKhachHang, tenKhachHang, soDienThoai, diaChi, diemTichLuy);

            if (isUpdated) {
                JOptionPane.showMessageDialog(this, "Cập nhật thông tin khách hàng thành công!");
                // Làm mới bảng và form
                ArrayList<KhachHang> list = repository.getAll();
                mol.setRowCount(0);
                for (KhachHang kh : list) {
                    mol.addRow(kh.toDataRow());
                }
                clearForm(); // Reset form sau khi sửa
            } else {
                JOptionPane.showMessageDialog(this, "Cập nhật thông tin khách hàng thất bại.");
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Đã xảy ra lỗi: " + ex.getMessage());
        }


    }//GEN-LAST:event_btnsuaActionPerformed


    private String getSafeString(Object value) {
        return value != null ? value.toString() : "";
    }

    public void fillTableKH(ArrayList<KhachHang> list) {
        mol.setRowCount(0); // Xóa dữ liệu cũ trong bảng
        for (KhachHang kh : list) {
            Object[] rowData = kh.toDataRow(); // Lấy dữ liệu từ toDataRow (5 cột: MaKH, TenKH, SoDT, DiaChi, DiemTichLuy)
            mol.addRow(rowData); // Thêm trực tiếp mảng rowData vào bảng
        }
        if (list.isEmpty()) {
            System.out.println("Cảnh báo: Danh sách khách hàng rỗng!");
        }
    }
    
